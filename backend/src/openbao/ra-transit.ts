/**
 * OpenBao Transit client for the SCEP RA key (opt-in, decision-018 migration).
 *
 * Scope: only the four Transit calls the SCEP RA needs, against the PKI Manager
 * OpenBao fork (oriolrius/openbao, branch pki-manager, verified at 0e3024e):
 *
 *   GET  <mount>/keys/<name>                       read and check the key policy
 *   POST <mount>/keys/<name>                       create the key (first provisioning only)
 *   POST <mount>/sign/<name>/sha2-256              RSASSA-PKCS1-v1_5 over a SHA-256 digest
 *   POST <mount>/session-key/pkcs1v15/<name>       fork-only: CMS session-key transport
 *
 * Rules:
 * - HTTPS only. `OPENBAO_CACERT` pins the trust anchors; no redirects are followed.
 * - The token comes from `OPENBAO_TOKEN_FILE`, read on every call, so an OpenBao
 *   Agent (or an operator) can rotate it without a restart. It never goes in a log.
 * - The key name is generated by the backend (`scep-ra-<uuid>`). Callers of the
 *   HTTP API cannot select a key: the name comes from the RA binding row.
 * - The key version is fixed in the binding and sent with every operation.
 * - Every response is checked (types, lengths, version, key policy). The RA key
 *   must be non-exportable, without plaintext backup, rsa-3072, and opted in to
 *   PKCS#1 v1.5 session-key transport.
 * - Errors carry the HTTP status and the request path only. The OpenBao error
 *   text stays in `detail` for the server log; it never reaches an API client.
 */
import { request as httpsRequest, Agent } from 'node:https';
import { readFileSync } from 'node:fs';
import { isAbsolute } from 'node:path';
import { X509Certificate, constants, createPublicKey, publicDecrypt, timingSafeEqual, type KeyObject } from 'node:crypto';

export const RA_KEY_PROVIDERS = ['cosmian', 'openbao'] as const;
export type RAKeyProvider = (typeof RA_KEY_PROVIDERS)[number];

/** RSA-3072: modulus size in bytes (signatures and CMS key-transport ciphertexts). */
export const RA_MODULUS_BYTES = 384;
const KEY_NAME = /^scep-ra-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const PATH_SEGMENTS = /^[A-Za-z0-9_-]{1,64}(\/[A-Za-z0-9_-]{1,64}){0,3}$/;
const TOKEN = /^[A-Za-z0-9._-]{8,512}$/;
const MAX_RESPONSE_BYTES = 64 * 1024;
// DigestInfo prefix of SHA-256 (RFC 8017 §9.2, note 1).
const SHA256_DIGEST_INFO = Buffer.from('3031300d060960864801650304020105000420', 'hex');

export class OpenBaoConfigError extends Error {}

export class OpenBaoError extends Error {
  /** OpenBao error text, for the server log only. */
  readonly detail: string;
  constructor(readonly status: number, readonly path: string, detail: string) {
    super(`OpenBao request failed (${status === 0 ? 'transport' : `HTTP ${status}`}) on ${path}`);
    this.detail = detail.slice(0, 500);
  }
}

/** A response that does not match what the RA requires. */
export class OpenBaoResponseError extends Error {}

export interface OpenBaoConfig {
  addr: URL;
  caPem?: string;
  tokenFile: string;
  mount: string;
  namespace?: string;
  timeoutMs: number;
}

/**
 * Provider for NEW SCEP RA bindings. Default `cosmian`. A binding keeps the
 * provider recorded with its key, whatever this setting says later.
 */
export function defaultRAKeyProvider(env: NodeJS.ProcessEnv = process.env): RAKeyProvider {
  const value = (env.SCEP_RA_KEY_PROVIDER ?? '').trim();
  if (value === '') return 'cosmian';
  if ((RA_KEY_PROVIDERS as readonly string[]).includes(value)) return value as RAKeyProvider;
  throw new OpenBaoConfigError('SCEP_RA_KEY_PROVIDER must be cosmian or openbao');
}

export function loadOpenBaoConfig(env: NodeJS.ProcessEnv = process.env): OpenBaoConfig {
  const rawAddr = env.OPENBAO_ADDR?.trim();
  if (!rawAddr) throw new OpenBaoConfigError('OPENBAO_ADDR is required for the OpenBao RA provider');
  let addr: URL;
  try { addr = new URL(rawAddr); } catch { throw new OpenBaoConfigError('OPENBAO_ADDR is not a URL'); }
  if (addr.protocol !== 'https:') throw new OpenBaoConfigError('OPENBAO_ADDR must use https');
  if (addr.username || addr.password || addr.search || addr.hash || (addr.pathname !== '/' && addr.pathname !== '')) {
    throw new OpenBaoConfigError('OPENBAO_ADDR must be scheme://host[:port] only');
  }
  let caPem: string | undefined;
  const caFile = env.OPENBAO_CACERT?.trim();
  if (caFile) {
    try {
      caPem = readFileSync(caFile, 'utf8');
      new X509Certificate(caPem); // at least the first certificate must parse
    } catch { throw new OpenBaoConfigError('OPENBAO_CACERT must be a readable PEM certificate file'); }
  }
  const tokenFile = env.OPENBAO_TOKEN_FILE?.trim();
  if (!tokenFile || !isAbsolute(tokenFile)) throw new OpenBaoConfigError('OPENBAO_TOKEN_FILE must be an absolute path');
  const mount = (env.OPENBAO_RA_MOUNT ?? 'pki-manager-ra').trim();
  if (!PATH_SEGMENTS.test(mount)) throw new OpenBaoConfigError('OPENBAO_RA_MOUNT is not a valid mount path');
  const namespace = env.OPENBAO_NAMESPACE?.trim() || undefined;
  if (namespace && !PATH_SEGMENTS.test(namespace)) throw new OpenBaoConfigError('OPENBAO_NAMESPACE is not a valid namespace path');
  const timeoutMs = env.OPENBAO_TIMEOUT_MS ? Number(env.OPENBAO_TIMEOUT_MS) : 10_000;
  if (!Number.isInteger(timeoutMs) || timeoutMs < 1000 || timeoutMs > 60_000) throw new OpenBaoConfigError('OPENBAO_TIMEOUT_MS must be 1000-60000');
  return { addr, caPem, tokenFile, mount, namespace, timeoutMs };
}

/** Standard base64 that round-trips exactly (no whitespace, no URL alphabet, canonical padding). */
function strictBase64(value: unknown): Buffer {
  if (typeof value !== 'string' || value.length === 0 || !/^[A-Za-z0-9+/]+={0,2}$/.test(value)) throw new OpenBaoResponseError('invalid base64 field');
  const bytes = Buffer.from(value, 'base64');
  if (bytes.toString('base64') !== value) throw new OpenBaoResponseError('non-canonical base64 field');
  return bytes;
}

type Json = Record<string, unknown>;
const isObject = (v: unknown): v is Json => typeof v === 'object' && v !== null && !Array.isArray(v);

export function assertKeyName(name: string): void {
  if (!KEY_NAME.test(name)) throw new OpenBaoResponseError('RA key name is not a backend-generated name');
}

/**
 * Checks a Transit key read response for the RA requirements and returns the
 * public key of `version`. Exported for tests.
 */
export function checkRAKeyPolicy(data: unknown, version: number): KeyObject {
  if (!isObject(data)) throw new OpenBaoResponseError('key response has no data');
  if (data.type !== 'rsa-3072') throw new OpenBaoResponseError('RA key must be rsa-3072');
  if (data.exportable !== false) throw new OpenBaoResponseError('RA key must not be exportable');
  if (data.allow_plaintext_backup !== false) throw new OpenBaoResponseError('RA key must not allow plaintext backup');
  if (data.allow_pkcs1v15_session_key !== true) throw new OpenBaoResponseError('RA key is not opted in to PKCS#1 v1.5 session-key transport');
  if (data.derived !== false) throw new OpenBaoResponseError('RA key must not be derived');
  if (data.deletion_allowed !== false) throw new OpenBaoResponseError('RA key must not allow deletion');
  const latest = data.latest_version, minDecrypt = data.min_decryption_version, minAvailable = data.min_available_version ?? 0;
  if (!Number.isInteger(latest) || !Number.isInteger(minDecrypt) || !Number.isInteger(minAvailable)) throw new OpenBaoResponseError('key versions missing');
  if ((latest as number) < version || (minDecrypt as number) > version || (minAvailable as number) > version) throw new OpenBaoResponseError('RA key version is not available');
  const keys = data.keys;
  const entry = isObject(keys) ? keys[String(version)] : undefined;
  if (!isObject(entry) || typeof entry.public_key !== 'string') throw new OpenBaoResponseError('RA key version has no public key');
  let key: KeyObject;
  try { key = createPublicKey(entry.public_key); } catch { throw new OpenBaoResponseError('RA public key does not parse'); }
  if (key.asymmetricKeyType !== 'rsa' || key.asymmetricKeyDetails?.modulusLength !== 3072) throw new OpenBaoResponseError('RA public key is not RSA-3072');
  return key;
}

/** Verifies an RSASSA-PKCS1-v1_5 SHA-256 signature over a digest (no OpenSSL CLI, Node crypto only). */
export function verifyDigestSignature(publicKey: KeyObject, digest: Buffer, signature: Buffer): boolean {
  if (signature.length !== RA_MODULUS_BYTES) return false;
  let recovered: Buffer;
  try { recovered = publicDecrypt({ key: publicKey, padding: constants.RSA_PKCS1_PADDING }, signature); } catch { return false; }
  const expected = Buffer.concat([SHA256_DIGEST_INFO, digest]);
  return recovered.length === expected.length && timingSafeEqual(recovered, expected);
}

export class OpenBaoRATransit {
  private readonly agent: Agent;
  constructor(private readonly cfg: OpenBaoConfig) {
    this.agent = new Agent({ keepAlive: true, maxSockets: 8, ca: cfg.caPem, rejectUnauthorized: true, minVersion: 'TLSv1.2' });
  }

  private token(): string {
    let token: string;
    try { token = readFileSync(this.cfg.tokenFile, 'utf8').trim(); } catch { throw new OpenBaoError(0, 'token', 'token file unreadable'); }
    if (!TOKEN.test(token)) throw new OpenBaoError(0, 'token', 'token file content is not a token');
    return token;
  }

  private call(method: 'GET' | 'POST', path: string, body?: Json): Promise<{ status: number; json: Json }> {
    const headers: Record<string, string> = { 'X-Vault-Token': this.token(), 'X-Vault-Request': 'true', accept: 'application/json' };
    if (this.cfg.namespace) headers['X-Vault-Namespace'] = this.cfg.namespace;
    const payload = body === undefined ? undefined : Buffer.from(JSON.stringify(body));
    if (payload) { headers['content-type'] = 'application/json'; headers['content-length'] = String(payload.length); }
    const url = new URL(`/v1/${this.cfg.mount}/${path}`, this.cfg.addr);
    return new Promise((resolve, reject) => {
      const req = httpsRequest(url, { method, headers, agent: this.agent, timeout: this.cfg.timeoutMs }, res => {
        const chunks: Buffer[] = [];
        let size = 0;
        res.on('data', (chunk: Buffer) => {
          size += chunk.length;
          if (size > MAX_RESPONSE_BYTES) { req.destroy(); reject(new OpenBaoError(res.statusCode ?? 0, path, 'response too large')); return; }
          chunks.push(chunk);
        });
        res.on('end', () => {
          const status = res.statusCode ?? 0;
          let json: Json = {};
          const text = Buffer.concat(chunks).toString('utf8');
          if (text) {
            try { const parsed: unknown = JSON.parse(text); if (isObject(parsed)) json = parsed; } catch { /* not JSON */ }
          }
          if (status >= 200 && status < 300) { resolve({ status, json }); return; }
          const errors = Array.isArray(json.errors) ? json.errors.filter(e => typeof e === 'string').join('; ') : '';
          reject(new OpenBaoError(status, path, errors));
        });
        res.on('error', error => reject(new OpenBaoError(res.statusCode ?? 0, path, String(error))));
      });
      req.on('timeout', () => req.destroy(new Error('timeout')));
      req.on('error', error => reject(error instanceof OpenBaoError ? error : new OpenBaoError(0, path, error.message)));
      if (payload) req.write(payload);
      req.end();
    });
  }

  /** Reads and checks the key; null when it does not exist. */
  async readKey(name: string, version: number): Promise<KeyObject | null> {
    assertKeyName(name);
    try {
      const { json } = await this.call('GET', `keys/${name}`);
      return checkRAKeyPolicy(json.data, version);
    } catch (error) {
      if (error instanceof OpenBaoError && error.status === 404) return null;
      throw error;
    }
  }

  /**
   * Returns the checked public key, and creates the key first when it does not
   * exist. Only provisioning calls this; a renewal uses `readKey`.
   */
  async ensureKey(name: string, version: number): Promise<KeyObject> {
    const existing = await this.readKey(name, version);
    if (existing) return existing;
    if (version !== 1) throw new OpenBaoResponseError('a new RA key starts at version 1');
    await this.call('POST', `keys/${name}`, {
      type: 'rsa-3072', exportable: false, allow_plaintext_backup: false, allow_pkcs1v15_session_key: true, auto_rotate_period: 0,
    });
    const created = await this.readKey(name, version);
    if (!created) throw new OpenBaoResponseError('RA key not readable after creation');
    return created;
  }

  /** RSASSA-PKCS1-v1_5 / SHA-256 over a 32-byte digest, checked against `publicKey`. */
  async signDigest(name: string, version: number, digest: Buffer, publicKey: KeyObject): Promise<Buffer> {
    assertKeyName(name);
    if (digest.length !== 32) throw new OpenBaoResponseError('SHA-256 digest required');
    const { json } = await this.call('POST', `sign/${name}/sha2-256`, {
      input: digest.toString('base64'), prehashed: true, signature_algorithm: 'pkcs1v15', key_version: version,
    });
    const data = json.data;
    const signature = isObject(data) ? data.signature : undefined;
    const prefix = `vault:v${version}:`;
    if (typeof signature !== 'string' || !signature.startsWith(prefix)) throw new OpenBaoResponseError('signature has the wrong key version');
    const bytes = strictBase64(signature.slice(prefix.length));
    if (!verifyDigestSignature(publicKey, digest, bytes)) throw new OpenBaoResponseError('signature does not verify with the RA public key');
    return bytes;
  }

  /** Fork operation: recovers a CMS session key of exactly `length` bytes. */
  async unwrapSessionKey(name: string, version: number, ciphertext: Buffer, length: 16 | 24 | 32): Promise<Buffer> {
    assertKeyName(name);
    if (ciphertext.length !== RA_MODULUS_BYTES) throw new OpenBaoResponseError('RSA-3072 ciphertext required');
    const { json } = await this.call('POST', `session-key/pkcs1v15/${name}`, {
      ciphertext: ciphertext.toString('base64'), key_version: version, session_key_length: length,
    });
    const data = json.data;
    if (!isObject(data) || data.key_version !== version) throw new OpenBaoResponseError('session key has the wrong key version');
    const key = strictBase64(data.session_key);
    if (key.length !== length) { key.fill(0); throw new OpenBaoResponseError('session key has the wrong length'); }
    return key;
  }
}

let cached: { transit: OpenBaoRATransit } | undefined;
/** Lazily configured client; config errors are thrown on first use. */
export function getOpenBaoRATransit(): OpenBaoRATransit {
  cached ??= { transit: new OpenBaoRATransit(loadOpenBaoConfig()) };
  return cached.transit;
}
/** Tests only. */
export function resetOpenBaoRATransit(): void { cached = undefined; }

/**
 * Startup check. Fails when SCEP_RA_KEY_PROVIDER is invalid, or when OpenBao is
 * needed (new bindings go to OpenBao, or a binding already uses it) and its
 * settings are invalid. With no OpenBao use at all, it checks nothing more.
 */
export function checkOpenBaoRAConfig(openBaoBindings: number, env: NodeJS.ProcessEnv = process.env): RAKeyProvider {
  const provider = defaultRAKeyProvider(env);
  if (provider === 'openbao' || openBaoBindings > 0 || env.OPENBAO_ADDR) loadOpenBaoConfig(env);
  return provider;
}
