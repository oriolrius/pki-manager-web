/**
 * OpenBao Transit client for the X.509 key store (decision-018, doc-012 §3).
 *
 * The X.509 CA and leaf keys live in the key mount (`OPENBAO_TRANSIT_MOUNT`, default
 * `pki-manager`; policy `openbao/policies/pki-manager-backend.hcl`). The SSH CA keys
 * (`ssh-transit.ts`) and the SCEP RA keys (`ra-transit.ts`) have their own clients. This
 * client only knows the Transit calls that the X.509 key store needs:
 *
 *   GET    <mount>/keys/<name>                          read the key policy and public keys
 *   POST   <mount>/keys/<name>                          create a key
 *   POST   <mount>/sign/<name>/<hash>                   sign (RSA PKCS#1 v1.5 or ECDSA ASN.1)
 *   GET    <mount>/export/signing-key/<name>/<version>  PKCS#8 export (exportable keys only)
 *   POST   <mount>/keys/<name>/config                   deletion_allowed=true (nothing else)
 *   DELETE <mount>/keys/<name>                          delete the key
 *   GET    sys/health                                   status check
 *
 * Rules (same as the SCEP RA client):
 * - HTTPS only. `OPENBAO_CACERT` pins the trust anchors. No redirect is followed.
 * - The token comes from `OPENBAO_TOKEN_FILE` and is read on every call, so an OpenBao Agent
 *   can rotate it. It never goes into a log or an error.
 * - Key names are generated by the backend and checked here; a request value never selects a key.
 * - Every operation pins a key version, and every response is checked.
 * - Errors carry the HTTP status and a path pattern. The OpenBao error text stays in `detail`.
 */
import { request as httpsRequest, Agent } from 'node:https';
import { readFileSync } from 'node:fs';
import { isAbsolute } from 'node:path';
import { X509Certificate, createPrivateKey, createPublicKey, type KeyObject } from 'node:crypto';

export type TransitKeyType = 'rsa-2048' | 'rsa-3072' | 'rsa-4096' | 'ecdsa-p256' | 'ecdsa-p384';
export const TRANSIT_KEY_TYPES: readonly TransitKeyType[] = ['rsa-2048', 'rsa-3072', 'rsa-4096', 'ecdsa-p256', 'ecdsa-p384'];
export type TransitHash = 'sha2-256' | 'sha2-384' | 'sha2-512';

const KEY_NAME = /^[a-z0-9][a-z0-9-]{0,62}[a-z0-9]$/;
const PATH_SEGMENTS = /^[A-Za-z0-9_-]{1,64}(\/[A-Za-z0-9_-]{1,64}){0,3}$/;
const TOKEN = /^[A-Za-z0-9._-]{8,512}$/;
const MAX_RESPONSE_BYTES = 256 * 1024;

export class OpenBaoTransitConfigError extends Error {}

export class OpenBaoTransitError extends Error {
  /** OpenBao error text, for the server log only. */
  readonly detail: string;
  /**
   * Set by `createKey` when OpenBao did not create the key: the first read failed, or the create
   * request got an answer that refuses it. Unset when the outcome is unknown.
   */
  keyNotCreated?: boolean;
  constructor(readonly status: number, readonly path: string, detail: string) {
    super(`OpenBao request failed (${status === 0 ? 'transport' : `HTTP ${status}`}) on ${path}`);
    this.detail = detail.slice(0, 500);
  }
}

/**
 * A create request that OpenBao refused with an answer (4xx, not initialized, sealed or standby),
 * or that was never sent (the token file failed): the key does not exist. A transport error after
 * the request was sent, or another 5xx, leaves the outcome unknown.
 */
function createRefused(error: unknown): boolean {
  if (!(error instanceof OpenBaoTransitError)) return false;
  if (error.status === 0) return error.path === 'token';
  return (error.status >= 400 && error.status < 500) || error.status === 501 || error.status === 503;
}

function markNotCreated(error: unknown): unknown {
  if (error instanceof OpenBaoTransitError) error.keyNotCreated = true;
  return error;
}

/** A response that does not match what the key store requires. */
export class OpenBaoTransitResponseError extends Error {}

export interface OpenBaoTransitConfig {
  addr: URL;
  caPem?: string;
  tokenFile: string;
  namespace?: string;
  timeoutMs: number;
  /** Transit mount of the X.509 CA and leaf keys. */
  mount: string;
  /**
   * Create new CA keys as exportable. Follows `ALLOW_CA_KEY_EXPORT` (default false): a CA
   * key that was created non-exportable can never be exported later.
   */
  caKeysExportable: boolean;
}

function parseBool(name: string, value: string | undefined, fallback: boolean): boolean {
  const v = (value ?? '').trim().toLowerCase();
  if (v === '') return fallback;
  if (v === 'true' || v === '1') return true;
  if (v === 'false' || v === '0') return false;
  throw new OpenBaoTransitConfigError(`${name} must be true or false`);
}

export function loadOpenBaoTransitConfig(env: NodeJS.ProcessEnv = process.env): OpenBaoTransitConfig {
  const rawAddr = env.OPENBAO_ADDR?.trim();
  if (!rawAddr) throw new OpenBaoTransitConfigError('OPENBAO_ADDR is required for the OpenBao key store');
  let addr: URL;
  try { addr = new URL(rawAddr); } catch { throw new OpenBaoTransitConfigError('OPENBAO_ADDR is not a URL'); }
  if (addr.protocol !== 'https:') throw new OpenBaoTransitConfigError('OPENBAO_ADDR must use https');
  if (addr.username || addr.password || addr.search || addr.hash || (addr.pathname !== '/' && addr.pathname !== '')) {
    throw new OpenBaoTransitConfigError('OPENBAO_ADDR must be scheme://host[:port] only');
  }
  let caPem: string | undefined;
  const caFile = env.OPENBAO_CACERT?.trim();
  if (caFile) {
    try {
      caPem = readFileSync(caFile, 'utf8');
      new X509Certificate(caPem);
    } catch { throw new OpenBaoTransitConfigError('OPENBAO_CACERT must be a readable PEM certificate file'); }
  }
  const tokenFile = env.OPENBAO_TOKEN_FILE?.trim();
  if (!tokenFile || !isAbsolute(tokenFile)) throw new OpenBaoTransitConfigError('OPENBAO_TOKEN_FILE must be an absolute path');
  const namespace = env.OPENBAO_NAMESPACE?.trim() || undefined;
  if (namespace && !PATH_SEGMENTS.test(namespace)) throw new OpenBaoTransitConfigError('OPENBAO_NAMESPACE is not a valid namespace path');
  const timeoutMs = env.OPENBAO_TIMEOUT_MS ? Number(env.OPENBAO_TIMEOUT_MS) : 10_000;
  if (!Number.isInteger(timeoutMs) || timeoutMs < 1000 || timeoutMs > 60_000) throw new OpenBaoTransitConfigError('OPENBAO_TIMEOUT_MS must be 1000-60000');
  const mount = (env.OPENBAO_TRANSIT_MOUNT ?? 'pki-manager').trim();
  if (!PATH_SEGMENTS.test(mount)) throw new OpenBaoTransitConfigError('OPENBAO_TRANSIT_MOUNT is not a valid mount path');
  const caKeysExportable = parseBool('ALLOW_CA_KEY_EXPORT', env.ALLOW_CA_KEY_EXPORT, false);
  return { addr, caPem, tokenFile, namespace, timeoutMs, mount, caKeysExportable };
}

type Json = Record<string, unknown>;
const isObject = (v: unknown): v is Json => typeof v === 'object' && v !== null && !Array.isArray(v);

function strictBase64(value: unknown): Buffer {
  if (typeof value !== 'string' || value.length === 0 || !/^[A-Za-z0-9+/]+={0,2}$/.test(value)) throw new OpenBaoTransitResponseError('invalid base64 field');
  const bytes = Buffer.from(value, 'base64');
  if (bytes.toString('base64') !== value) throw new OpenBaoTransitResponseError('non-canonical base64 field');
  return bytes;
}

export function assertTransitKeyName(name: string): void {
  if (!KEY_NAME.test(name)) throw new OpenBaoTransitResponseError('key name is not a backend-generated name');
}

function assertMount(mount: string): void {
  if (!PATH_SEGMENTS.test(mount)) throw new OpenBaoTransitResponseError('invalid mount');
}

/** What the key store needs from `GET keys/<name>`. */
export interface TransitKeyInfo {
  type: TransitKeyType;
  exportable: boolean;
  allowPlaintextBackup: boolean;
  softDeleted: boolean;
  importedKey: boolean;
  latestVersion: number;
  minAvailableVersion: number;
  /** Public key of each version, by version number. */
  publicKeys: Map<number, KeyObject>;
}

/** Parse and check a Transit key read response. Exported for tests. */
export function parseTransitKey(data: unknown): TransitKeyInfo {
  if (!isObject(data)) throw new OpenBaoTransitResponseError('key response has no data');
  if (typeof data.type !== 'string' || !(TRANSIT_KEY_TYPES as readonly string[]).includes(data.type)) {
    throw new OpenBaoTransitResponseError('key type is not supported by the key store');
  }
  if (data.derived === true) throw new OpenBaoTransitResponseError('derived keys are not supported');
  if (typeof data.exportable !== 'boolean') throw new OpenBaoTransitResponseError('key policy has no exportable flag');
  const latest = data.latest_version;
  const minAvailable = data.min_available_version ?? 0;
  if (!Number.isInteger(latest) || !Number.isInteger(minAvailable)) throw new OpenBaoTransitResponseError('key versions missing');
  const publicKeys = new Map<number, KeyObject>();
  if (isObject(data.keys)) {
    for (const [version, entry] of Object.entries(data.keys)) {
      if (!/^[1-9]\d{0,5}$/.test(version) || !isObject(entry) || typeof entry.public_key !== 'string') continue;
      try { publicKeys.set(Number(version), createPublicKey(entry.public_key)); } catch { throw new OpenBaoTransitResponseError('public key does not parse'); }
    }
  }
  return {
    type: data.type as TransitKeyType,
    exportable: data.exportable,
    allowPlaintextBackup: data.allow_plaintext_backup === true,
    softDeleted: data.soft_deleted === true,
    importedKey: data.imported_key === true,
    latestVersion: latest as number,
    minAvailableVersion: minAvailable as number,
    publicKeys,
  };
}

/** Check that a public key matches a Transit key type. */
export function assertKeyMatchesType(key: KeyObject, type: TransitKeyType): void {
  const details = key.asymmetricKeyDetails;
  const ok = type.startsWith('rsa-')
    ? key.asymmetricKeyType === 'rsa' && details?.modulusLength === Number(type.slice(4))
    : key.asymmetricKeyType === 'ec' && details?.namedCurve === (type === 'ecdsa-p256' ? 'prime256v1' : 'secp384r1');
  if (!ok) throw new OpenBaoTransitResponseError(`public key does not match key type ${type}`);
}

export class OpenBaoTransitClient {
  private readonly agent: Agent;
  constructor(readonly cfg: OpenBaoTransitConfig) {
    this.agent = new Agent({ keepAlive: true, maxSockets: 16, ca: cfg.caPem, rejectUnauthorized: true, minVersion: 'TLSv1.2' });
  }

  private token(): string {
    let token: string;
    try { token = readFileSync(this.cfg.tokenFile, 'utf8').trim(); } catch { throw new OpenBaoTransitError(0, 'token', 'token file unreadable'); }
    if (!TOKEN.test(token)) throw new OpenBaoTransitError(0, 'token', 'token file content is not a token');
    return token;
  }

  private call(method: 'GET' | 'POST' | 'DELETE', path: string, label: string, body?: Json, auth = true): Promise<{ status: number; json: Json }> {
    const headers: Record<string, string> = { 'X-Vault-Request': 'true', accept: 'application/json' };
    if (auth) headers['X-Vault-Token'] = this.token();
    if (this.cfg.namespace) headers['X-Vault-Namespace'] = this.cfg.namespace;
    const payload = body === undefined ? undefined : Buffer.from(JSON.stringify(body));
    if (payload) { headers['content-type'] = 'application/json'; headers['content-length'] = String(payload.length); }
    const url = new URL(`/v1/${path}`, this.cfg.addr);
    return new Promise((resolve, reject) => {
      const req = httpsRequest(url, { method, headers, agent: this.agent, timeout: this.cfg.timeoutMs }, (res) => {
        const chunks: Buffer[] = [];
        let size = 0;
        res.on('data', (chunk: Buffer) => {
          size += chunk.length;
          if (size > MAX_RESPONSE_BYTES) { req.destroy(); reject(new OpenBaoTransitError(res.statusCode ?? 0, label, 'response too large')); return; }
          chunks.push(chunk);
        });
        res.on('end', () => {
          const status = res.statusCode ?? 0;
          let json: Json = {};
          const text = Buffer.concat(chunks).toString('utf8');
          if (text) {
            try { const parsed: unknown = JSON.parse(text); if (isObject(parsed)) json = parsed; } catch { /* not JSON */ }
          }
          if (status >= 200 && status < 300) { resolve({ status, json }); return; }
          const errors = Array.isArray(json.errors) ? json.errors.filter((e) => typeof e === 'string').join('; ') : '';
          reject(new OpenBaoTransitError(status, label, errors));
        });
        res.on('error', (error) => reject(new OpenBaoTransitError(res.statusCode ?? 0, label, String(error))));
      });
      req.on('timeout', () => req.destroy(new Error('timeout')));
      req.on('error', (error) => reject(error instanceof OpenBaoTransitError ? error : new OpenBaoTransitError(0, label, error.message)));
      if (payload) req.write(payload);
      req.end();
    });
  }

  /** Reads the key; null when it does not exist. */
  async readKey(mount: string, name: string): Promise<TransitKeyInfo | null> {
    assertMount(mount);
    assertTransitKeyName(name);
    try {
      const { json } = await this.call('GET', `${mount}/keys/${name}`, 'keys/<name>');
      return parseTransitKey(json.data);
    } catch (error) {
      if (error instanceof OpenBaoTransitError && error.status === 404) return null;
      throw error;
    }
  }

  /**
   * Creates a key and returns its checked policy. A key that already exists with the same type
   * and export setting is reused (a retry after a lost response); any other existing key is
   * an error.
   */
  async createKey(mount: string, name: string, type: TransitKeyType, exportable: boolean): Promise<TransitKeyInfo> {
    assertMount(mount);
    assertTransitKeyName(name);
    let existing: TransitKeyInfo | null;
    try {
      existing = await this.readKey(mount, name);
    } catch (error) {
      throw markNotCreated(error);
    }
    if (!existing) {
      try {
        await this.call('POST', `${mount}/keys/${name}`, 'keys/<name>', {
          type, exportable, allow_plaintext_backup: false, auto_rotate_period: 0,
        });
      } catch (error) {
        throw createRefused(error) ? markNotCreated(error) : error;
      }
    }
    const info = existing ?? (await this.readKey(mount, name));
    if (!info) throw new OpenBaoTransitResponseError('key not readable after creation');
    if (info.type !== type || info.exportable !== exportable || info.importedKey || info.softDeleted || info.allowPlaintextBackup) {
      throw new OpenBaoTransitResponseError('existing key does not have the requested policy');
    }
    const pub = info.publicKeys.get(1);
    if (info.latestVersion < 1 || !pub) throw new OpenBaoTransitResponseError('key has no version 1');
    assertKeyMatchesType(pub, type);
    return info;
  }

  /**
   * Signs `input` with version `version`. RSA uses PKCS#1 v1.5 (with DigestInfo), ECDSA
   * returns a DER signature. With `prehashed`, `input` is the digest.
   */
  async sign(mount: string, name: string, version: number, hash: TransitHash, input: Buffer, opts: { rsa: boolean; prehashed?: boolean }): Promise<Buffer> {
    assertMount(mount);
    assertTransitKeyName(name);
    if (!Number.isInteger(version) || version < 1) throw new OpenBaoTransitResponseError('invalid key version');
    const body: Json = { input: input.toString('base64'), key_version: version, prehashed: opts.prehashed === true };
    if (opts.rsa) body.signature_algorithm = 'pkcs1v15';
    else body.marshaling_algorithm = 'asn1';
    const { json } = await this.call('POST', `${mount}/sign/${name}/${hash}`, 'sign/<name>', body);
    const data = json.data;
    const signature = isObject(data) ? data.signature : undefined;
    const prefix = `vault:v${version}:`;
    if (typeof signature !== 'string' || !signature.startsWith(prefix)) throw new OpenBaoTransitResponseError('signature has the wrong key version');
    return strictBase64(signature.slice(prefix.length));
  }

  /** PKCS#8 PEM of version `version`. OpenBao refuses non-exportable keys. */
  async exportPrivateKeyPkcs8(mount: string, name: string, version: number): Promise<string> {
    assertMount(mount);
    assertTransitKeyName(name);
    const { json } = await this.call('GET', `${mount}/export/signing-key/${name}/${version}?format=pem`, 'export/signing-key/<name>');
    const data = json.data;
    const keys = isObject(data) && isObject(data.keys) ? data.keys : undefined;
    const pem = keys?.[String(version)];
    if (typeof pem !== 'string') throw new OpenBaoTransitResponseError('export response has no key');
    let key: KeyObject;
    try { key = createPrivateKey(pem); } catch { throw new OpenBaoTransitResponseError('exported key does not parse'); }
    return key.export({ type: 'pkcs8', format: 'pem' }).toString();
  }

  /**
   * Delete the key for good: allow deletion (the only config change the backend policy
   * permits), then delete. A key that no longer exists is not an error.
   */
  async deleteKey(mount: string, name: string): Promise<void> {
    assertMount(mount);
    assertTransitKeyName(name);
    if (!(await this.readKey(mount, name))) return;
    try {
      await this.call('POST', `${mount}/keys/${name}/config`, 'keys/<name>/config', { deletion_allowed: true });
      await this.call('DELETE', `${mount}/keys/${name}`, 'keys/<name>');
    } catch (error) {
      if (error instanceof OpenBaoTransitError && error.status === 404) return;
      throw error;
    }
  }

  /** `sys/health` without a token: initialized, sealed, standby. */
  async health(): Promise<{ initialized: boolean; sealed: boolean; standby: boolean }> {
    try {
      const { json } = await this.call('GET', 'sys/health?standbyok=true&perfstandbyok=true', 'sys/health', undefined, false);
      return { initialized: json.initialized === true, sealed: json.sealed === true, standby: json.standby === true };
    } catch (error) {
      // 501 = not initialized, 503 = sealed: the body still has the fields.
      if (error instanceof OpenBaoTransitError && (error.status === 501 || error.status === 503)) {
        return { initialized: error.status !== 501, sealed: error.status === 503, standby: false };
      }
      throw error;
    }
  }

  /**
   * The token can use the key mount: reads a key name that the backend never creates. The
   * backend policy has no default policy (no `lookup-self`), so this is the cheapest check.
   */
  async tokenValid(): Promise<boolean> {
    try {
      await this.readKey(this.cfg.mount, 'status-probe');
      return true;
    } catch (error) {
      if (error instanceof OpenBaoTransitError && error.status === 403) return false;
      throw error;
    }
  }
}

let cached: OpenBaoTransitClient | undefined;
/** Lazily configured client; config errors are thrown on first use. */
export function getOpenBaoTransitClient(): OpenBaoTransitClient {
  cached ??= new OpenBaoTransitClient(loadOpenBaoTransitConfig());
  return cached;
}
/** Tests only. */
export function resetOpenBaoTransitClient(): void { cached = undefined; }
